function vector(name, width, height, body) {
  const source = `art/source/generated/${name}.svg`;
  fs.writeFileSync(source, `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}"><g fill="white" stroke="black" stroke-width="5" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>`);
  convert(`garden-${name}`, source, `${width}x${height}`);
}
