// Rebuild with Node + ImageMagick. Generated art is resized once at authoring time;
// runtime stickers always use these native pixel dimensions with no resampling.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const out = 'src/assets/stickers';
const work = 'work/garden';
fs.mkdirSync(work, { recursive: true });
const pack = (bits) => {
  const bytes = Buffer.alloc(Math.ceil(bits.length / 8));
  bits.forEach((v, i) => { if (v) bytes[i >> 3] |= 1 << (i & 7); });
  return bytes.toString('base64');
};
const path = (bits, w, h) => {
  let d = '';
  for (let y = 0; y < h; y++) for (let x = 0; x < w;) {
    if (!bits[y * w + x]) { x++; continue; }
    const start = x;
    while (x < w && bits[y * w + x]) x++;
    d += `M${start} ${y}h${x - start}v1H${start}z`;
  }
  return d;
};
const masks = {};
function convert(name, source, size) {
  const png = `${work}/${name}.png`;
  execFileSync('magick', ['-background', 'none', source, '-trim', '+repage', '-resize', size, png]);
  const [width, height] = execFileSync('magick', ['identify', '-format', '%w %h', png]).toString().split(' ').map(Number);
  const pixels = execFileSync('magick', [png, '-depth', '8', 'rgba:-'], { maxBuffer: 16000000 });
  const coverage = new Uint8Array(width * height), outline = new Uint8Array(width * height);
  for (let i = 0; i < coverage.length; i++) {
    coverage[i] = pixels[i * 4 + 3] >= 128 ? 1 : 0;
    outline[i] = coverage[i] && pixels[i * 4] + pixels[i * 4 + 1] + pixels[i * 4 + 2] < 384 ? 1 : 0;
  }
  // Generated alpha edges sometimes omit the ink at the very perimeter.
  // Close every silhouette with a two-pixel inner border so bucket regions stay sealed.
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const i = y * width + x;
    if (!coverage[i]) continue;
    for (const [dx, dy] of [[-2, 0], [2, 0], [0, -2], [0, 2]]) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= width || ny >= height || !coverage[ny * width + nx]) outline[i] = 1;
    }
  }
  masks[name] = { width, height, coverage: pack(coverage), outline: pack(outline) };
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" shape-rendering="crispEdges"><path fill="white" d="${path(coverage, width, height)}"/><path fill="black" d="${path(outline, width, height)}"/></svg>`;
  fs.writeFileSync(`${out}/${name}.svg`, svg);
  // Palette PNG contains only black, white and transparent pixels; masks are 1 bit each.
  execFileSync('magick', ['-background', 'none', `${out}/${name}.svg`, '-channel', 'RGBA', '-threshold', '50%', '+channel', `PNG8:${out}/${name}.png`]);
}
for (const [name, size] of [['house', '680x560'], ['tree', '450x530'], ['bush', '300x150'], ['flower', '200x330'], ['mushroom', '150x185']]) {
  convert(`garden-${name}`, `art/source/generated/${name}.png`, size);
}
