// Rebuild with Node + ImageMagick. Generated art is resized once at authoring time;
// runtime stickers always use these native pixel dimensions with no resampling.
import fs from 'node:fs';
import { execFileSync } from 'node:child_process';
const out = 'src/assets/stickers';
const work = 'work/spring';
fs.mkdirSync(work, { recursive: true });
const pack = (bits) => {
  const bytes = Buffer.alloc(Math.ceil(bits.length / 8));
  bits.forEach((v, i) => { if (v) bytes[i >> 3] |= 1 << (i & 7); });
  return bytes.toString('base64');
};
const path = (bits, w, h) => {
  let d = '';
  for (let y = 0; y < h; y++) for (let x = 0; x < w;) {
    if (!bits[y * w + x]) { x++; continue; }
    const start = x;
    while (x < w && bits[y * w + x]) x++;
    d += `M${start} ${y}h${x - start}v1H${start}z`;
  }
  return d;
};
const masks = {};
function convert(name, source, size) {
  const png = `${work}/${name}.png`;
  execFileSync('magick', ['-background', 'none', source, '-trim', '+repage', '-resize', size, png]);
  const [width, height] = execFileSync('magick', ['identify', '-format', '%w %h', png]).toString().split(' ').map(Number);
  const pixels = execFileSync('magick', [png, '-depth', '8', 'rgba:-'], { maxBuffer: 16000000 });
  const coverage = new Uint8Array(width * height), outline = new Uint8Array(width * height);
  for (let i = 0; i < coverage.length; i++) {
    coverage[i] = pixels[i * 4 + 3] >= 128 ? 1 : 0;
    outline[i] = coverage[i] && pixels[i * 4] + pixels[i * 4 + 1] + pixels[i * 4 + 2] < 384 ? 1 : 0;
  }
  // Generated alpha edges sometimes omit the ink at the very perimeter.
  // Close every silhouette with a three-pixel inner border so bucket regions stay sealed.
  for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
    const i = y * width + x;
    if (!coverage[i]) continue;
    for (const [dx, dy] of [[-3, 0], [3, 0], [0, -3], [0, 3]]) {
      const nx = x + dx, ny = y + dy;
      if (nx < 0 || ny < 0 || nx >= width || ny >= height || !coverage[ny * width + nx]) outline[i] = 1;
    }
  }
  if (['spring-bunny', 'spring-butterfly', 'spring-tulip', 'spring-bird', 'spring-watering-can'].includes(name)) {
    const ink = outline.slice();
    for (let y = 0; y < height; y++) for (let x = 0; x < width; x++) {
      const i = y * width + x;
      if (!coverage[i]) continue;
      for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) {
        const nx = x + dx, ny = y + dy;
        if (nx >= 0 && ny >= 0 && nx < width && ny < height && ink[ny * width + nx]) outline[i] = 1;
      }
    }
  }
  masks[name] = { width, height, coverage: pack(coverage), outline: pack(outline) };
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" shape-rendering="crispEdges"><path fill="white" d="${path(coverage, width, height)}"/><path fill="black" d="${path(outline, width, height)}"/></svg>`;
  fs.writeFileSync(`${out}/${name}.svg`, svg);
  // Palette PNG contains only black, white and transparent pixels; masks are 1 bit each.
  execFileSync('magick', ['-background', 'none', `${out}/${name}.svg`, '-channel', 'RGBA', '-threshold', '50%', '+channel', `PNG8:${out}/${name}.png`]);
}
for (const [name, size] of [['bunny', '450x460'], ['butterfly', '320x260'], ['tulip', '300x420'], ['bird', '350x300'], ['watering-can', '380x340']]) {
  convert(`spring-${name}`, `art/source/spring/${name}.png`, size);
}
function vector(name, width, height, body) {
  const source = `art/source/spring/${name}.svg`;
  fs.writeFileSync(source, `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}"><g fill="white" stroke="black" stroke-width="5" stroke-linecap="round" stroke-linejoin="round">${body}</g></svg>`);
  convert(`spring-${name}`, source, `${width}x${height}`);
}
vector('meadow', 1920, 400, '<path d="M3 180Q450 -80 980 120T1917 100V397H3Z"/>');
vector('sun', 260, 260, '<circle cx="130" cy="130" r="125"/><circle cx="92" cy="113" r="5" fill="black"/><circle cx="168" cy="113" r="5" fill="black"/><path fill="none" d="M95 153Q130 188 165 153"/>');
vector('cloud', 380, 180, '<path d="M65 174C-10 174-10 75 58 70C50 0 152-15 176 54C206 5 290 15 301 72C395 50 402 174 315 174Z"/>');
fs.writeFileSync(`${out}/springMasks.ts`, `// Generated by scripts/build-spring-pack.mjs. Binary native-size masks.\nexport const springMasks = ${JSON.stringify(masks)} as const;\n`);
const placements = [['spring-meadow',960,775],['spring-sun',220,180],['spring-cloud',590,140],['spring-cloud',1600,150],['spring-butterfly',970,280],['spring-bird',1360,780],['spring-tulip',250,650],['spring-tulip',1660,700],['spring-bunny',1020,680],['spring-watering-can',560,760]];
let body = '<rect width="1920" height="960" fill="white"/>';
for (const [name,x,y] of placements) {
  const data=masks[name];
  const svg=fs.readFileSync(`${out}/${name}.svg`,'utf8').replace(/^<svg[^>]*>/,'').replace(/<\/svg>$/,'');
  body+=`<g transform="translate(${x-Math.floor(data.width/2)} ${y-Math.floor(data.height/2)})">${svg}</g>`;
}
fs.writeFileSync(`${work}/scene.svg`,`<svg xmlns="http://www.w3.org/2000/svg" width="1920" height="960" shape-rendering="crispEdges">${body}</svg>`);
execFileSync('magick',[`${work}/scene.svg`,'-threshold','50%',`${work}/scene.png`]);
console.log('Created eight spring stickers and scene preview.');


